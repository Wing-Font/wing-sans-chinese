#!/usr/bin/env python3
"""Build every Wing Sans family into fonts/ttf/.

    python3 build.py                  # fetch + verify inputs, build all, write metadata
    python3 build.py jyutping tailo   # only families whose name contains these words
    python3 build.py --fetch-only     # just fetch + verify inputs (then e.g. gftools builder config.yaml)
    python3 build.py --pin PATH...    # (re)download PATH from its URL and record its sha256
    python3 build.py --config         # regenerate config.yaml from tools/families.py

Inputs are locked in upstream_sources.json (URL + sha256): base fonts are
committed under srcfonts/, mapping CSVs are downloaded into mappings/ from the
wing-font-generator tag that matches requirements.txt. Release builds run from
a git tag (see .github/workflows/build.yml).
"""
import argparse
import hashlib
import json
import pathlib
import shutil
import subprocess
import sys
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT / "tools"))
from families import FAMILIES, VERSION, gf_dir, ps_name  # noqa: E402

SOURCES = ROOT / "upstream_sources.json"
# Browsers start the DIY mark's Latin run ~0.125 em right of where Word does
# (HYBRID_ANNOTATION_DESIGN.md, "Cross-run positioning"). Google Fonts is used
# mostly in browsers and Google Docs, so centre for them; Word shows it 0.125 em left.
MARK_X_OFFSET = "-0.125"
COPYRIGHT_LINE = "Copyright 2026 The Wing Sans Project Authors (https://github.com/Wing-Font/wing-sans-chinese)"


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def download(url, dest):
    dest.parent.mkdir(parents=True, exist_ok=True)
    print(f"  ⇣ {url}")
    req = urllib.request.Request(url, headers={"User-Agent": "wing-sans-build"})
    with urllib.request.urlopen(req) as r:
        dest.write_bytes(r.read())


def fetch_and_verify(sources):
    for rel, src in sources.items():
        path = ROOT / rel
        if not path.is_file():
            download(src["url"], path)
        got = sha256(path)
        if got != src["sha256"]:
            sys.exit(f"sha256 mismatch for {rel}: got {got}, locked {src['sha256']}.\n"
                     f"  Delete it to re-download, or run `build.py --pin {rel}` if the change is intended.")
    print(f"{len(sources)} inputs verified")


def generator_cmd(f):
    cmd = ["wing-font", "-i", f["base"], "-a", f["anno"], "-m", f["mapping"],
           "-f", f["family"], "-opt", "--no-woff2", "--font-version", VERSION, "--copyright-line", COPYRIGHT_LINE, *f["args"]]
    if f["diy"]:
        cmd += ["--diy-annotations", f["diy"], "--mark-x-offset", MARK_X_OFFSET]
    return cmd


def build(f):
    out = ROOT / "build" / ps_name(f)
    cmd = generator_cmd(f) + ["-o", str(out)]
    print("\n$ " + " ".join(cmd), flush=True)
    subprocess.run(cmd, cwd=ROOT, check=True)
    (ROOT / "fonts" / "ttf").mkdir(parents=True, exist_ok=True)
    shutil.copyfile(out.with_suffix(".ttf"), ROOT / "fonts" / "ttf" / f"{ps_name(f)}.ttf")


def write_config():
    """gftools builder recipe: one exec step per family running the generator."""
    lines = ["# Generated by `python3 build.py --config` — edit tools/families.py instead.",
             "# Run `python3 build.py --fetch-only` first so mappings/ exists.",
             "recipe:"]
    for f in FAMILIES:
        args = generator_cmd(f)[1:]
        # The generator takes an output *prefix*; $out ends in .ttf.
        args = [a if a != f["base"] else "$in" for a in args] + ["-o", f"fonts/ttf/{ps_name(f)}"]
        quoted = " ".join(f"'{a}'" if any(c in a for c in " []{},") else a for a in args)
        lines += [f"  fonts/ttf/{ps_name(f)}.ttf:",
                  f"    - source: {f['base']}",
                  "    - operation: exec",
                  "      exe: wing-font",
                  f"      args: >-\n        {quoted}"]
    (ROOT / "config.yaml").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote config.yaml")


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("only", nargs="*", help="build only families whose name contains these words, e.g. jyutping (default: all)")
    p.add_argument("--fetch-only", action="store_true")
    p.add_argument("--pin", nargs="+", metavar="PATH")
    p.add_argument("--config", action="store_true")
    a = p.parse_args()

    sources = json.loads(SOURCES.read_text(encoding="utf-8"))
    if a.pin:
        for rel in a.pin:
            download(sources[rel]["url"], ROOT / rel)
            sources[rel]["sha256"] = sha256(ROOT / rel)
        SOURCES.write_text(json.dumps(sources, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        return
    if a.config:
        return write_config()

    fetch_and_verify(sources)
    if a.fetch_only:
        return
    for f in FAMILIES:
        if not a.only or any(o.lower() in gf_dir(f) for o in a.only):
            build(f)
    subprocess.run([sys.executable, str(ROOT / "tools" / "gen_metadata.py")], check=True)


if __name__ == "__main__":
    main()
